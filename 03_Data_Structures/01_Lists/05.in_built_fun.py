num = [1, 24, 5, 74, 10, 4, 15]
fruits = ["orange", "apple", "banana"]

print(sum(num))

print("===============================================")

print(max(num))
print(max(fruits))

print("===============================================")

print(min(num))
print(min(fruits))

print("===============================================")

num.sort()
fruits.sort()
print(num)
print(sorted(fruits))

print("===============================================")

num.reverse()
fruits.reverse()
print(num)
print(fruits)   
